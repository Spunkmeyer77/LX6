#!/usr/bin/env python3
"""Generate Source/LxrParamTable.h from the LXR firmware sources (menu.c, MenuText.h, Parameters.h).
Usage: gen_params.py <lxr Core dir> <output header>"""
import re, sys
core, out = sys.argv[1], sys.argv[2]
menu = open(core + '/Src/menu/menu.c', encoding='latin-1').read()
mtext = open(core + '/Inc/menu/MenuText.h', encoding='latin-1').read()
params_h = open(core + '/Inc/Parameters.h', encoding='latin-1').read()

NUM = 247  # END_OF_SOUND_PARAMETERS in Parameters.h

# --- dtype table
tbl = menu[menu.index('parameter_dtypes[NUM_PARAMS] = {'):]
tbl = tbl[:tbl.index('};')]
entries = re.findall(r'/\*\s*([A-Za-z0-9_]+),?\s*\*/\s*([^,]+?)\s*,', tbl)

# --- menu option names
menu_ids = dict((m, int(n)) for m, n in re.findall(r'#define (MENU_[A-Z_]+)\s+(\d+)', mtext))
menu_arr = {'MENU_FILTER':'filterTypes','MENU_WAVEFORM':'waveformNames','MENU_AUDIO_OUT':'outputNames',
 'MENU_SYNC_RATES':'syncRateNames','MENU_LFO_WAVES':'lfoWaveNames','MENU_RETRIGGER':'retriggerNames',
 'MENU_TRANS':'transientNames','MENU_MIX_FM':'mixFmNames','MENU_FX':'fxNames','MENU_DIST':'distNames',
 'MENU_RATIO':'ratioNames','MENU_DELAY':'delayNames','MENU_REVERB':'reverbNames','MENU_AUDIO_OUT_FX':'outputNamesFx',
 'MENU_ROLL_RATES':'rollRateNames'}
src_all = mtext + menu
def options(arr):
    m = re.search(r'const char\s+%s\s*\[\]\s*\[\d+\]\s*=\s*\{(.*?)\};' % arr, src_all, re.S)
    if not m: return None
    items = re.findall(r'\{([^}]*)\}|"((?:[^"\\]|\\.)*)"', m.group(1))
    vals = []
    for a, b in items:
        if a:
            vals.append(a)
        else:
            vals.append(b)
    # first element is the count
    first = vals[0]
    cnt = None
    mm = re.search(r'(\d+)', first)
    if mm: cnt = int(mm.group(1))
    if first.startswith('\\x') or first.strip().startswith("'"):
        pass
    opts = [x.strip() for x in vals[1:]]
    if cnt is None: cnt = len(opts)
    return opts[:cnt]

rows = []
for i, (pname, dt) in enumerate(entries[:NUM]):
    kind, mx, opts = 'u127', 127, []
    d = dt.replace(' ', '')
    if 'DTYPE_MENU' in d:
        mid = re.search(r'\((MENU_[A-Z_]+)<<8\)', d).group(1)
        o = options(menu_arr.get(mid, '')) if mid in menu_arr else None
        kind = 'menu'; opts = o or []
        mx = max(len(opts) - 1, 0)
    elif 'DTYPE_PM63' in d: kind, mx = 'pm63', 127
    elif 'DTYPE_0B255' in d: kind, mx = 'u255', 255
    elif 'DTYPE_ON_OFF' in d or 'DTYPE_0b1' in d: kind, mx = 'onoff', 1
    elif 'DTYPE_1B16' in d: kind, mx = 'u1b16', 15
    elif 'DTYPE_0B15' in d: kind, mx = 'u15', 15
    elif 'DTYPE_0B100' in d: kind, mx = 'u100', 100
    elif 'DTYPE_PM100' in d: kind, mx = 'pm100', 127
    elif 'TARGET_SELECTION' in d: kind, mx = 'modtarget', 255
    elif 'DTYPE_VOICE_LFO' in d: kind, mx = 'voice', 6
    rows.append((i, pname, kind, mx, opts))

with open(out, 'w') as f:
    f.write('// Generated by tools/gen_params.py from the LXR firmware sources. Do not edit.\n')
    f.write('// SPDX-License-Identifier: GPL-3.0-only\n#pragma once\n\nnamespace lxr {\n')
    f.write('enum class Kind { u127, pm63, u255, onoff, u1b16, u15, u100, pm100, menu, modtarget, voice };\n')
    f.write('struct ParamInfo { int nr; const char* id; Kind kind; int maxValue; const char* options; };\n')
    f.write('static constexpr int numParamInfos = %d;\n' % len(rows))
    f.write('static const ParamInfo paramInfos[numParamInfos] = {\n')
    for i, pn, k, mx, o in rows:
        os = '|'.join(x.strip().replace('"', '') for x in o)
        f.write('  { %d, "%s", Kind::%s, %d, "%s" },\n' % (i, pn, k, mx, os))
    f.write('};\n}\n')
print(len(rows), 'params written')

# --- mod targets (LFO / velocity destinations), from Cc2Text.c
cc2 = open(core + '/Src/menu/Cc2Text.c', encoding='latin-1').read()
mt = cc2[cc2.index('const ModTarg modTargets[] ={'):]
mt = mt[:mt.index('};')]
mt = re.sub(r'//.*', '', mt)
pairs = re.findall(r'\{\s*([A-Z_0-9]+)\s*,\s*([A-Z_0-9]+)\s*\}', mt)
ids = [r[1] for r in rows]
alias = {'PAR_NONE': 0}
nums = []
for _, par in pairs:
    if par in alias: nums.append(alias[par]); continue
    if par in ids: nums.append(ids.index(par)); continue
    raise SystemExit('unknown mod target ' + par)
with open(out, 'a') as f:
    f.write('namespace lxr {\nstatic const int modTargetParams[] = { %s };\n' % ', '.join(map(str, nums)))
    f.write('static constexpr int numModTargets = %d;\n}\n' % len(nums))
print(len(nums), 'mod targets')

# --- init kit defaults
ik = open(core + '/Src/Preset/initKit.c', encoding='latin-1').read()
arr = ik[ik.index('{')+1:ik.index('}')]
vals = [int(x, 16) for x in re.findall(r'0x[0-9a-fA-F]+', arr)]
defaults = [vals[i + 8] if i + 8 < len(vals) else 0 for i in range(NUM)]
with open(out, 'a') as f:
    f.write('namespace lxr {\nstatic const unsigned char initKitDefaults[%d] = { %s };\n}\n' % (NUM, ', '.join(map(str, defaults))))
print('init kit defaults written')
